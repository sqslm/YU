/**
 * The diagnostic launch wrapper.
 *
 * `app.setLoginItemSettings` is called unconditionally on every start
 * (src/main/index.ts), and it writes HKCU — which `--user-data-dir` does not
 * isolate. The wrapper is the only thing this benchmark does about that: it
 * replaces the call with a log line. It never removes or rewrites a startup
 * entry, and it records every invocation so the evidence can show that a write
 * was attempted and suppressed, not merely absent.
 *
 * Both sides run the exact same bytes; the sha256 goes into the evidence so a
 * stale wrapper cannot pass unnoticed. The file is generated idempotently and
 * carries no timestamp, so re-running leaves it untouched.
 */
import { createHash } from 'node:crypto'
import fs from 'node:fs'
import { dirname, join } from 'node:path'

export const ENTRY_FILENAME = 'index.js'
export const WRAPPER_FILENAME = 'diagnostic-entry.cjs'
/** Path relative to the app root. Same directory as the entry, so `app.getAppPath()` does not move. */
export const WRAPPER_RELATIVE = `out/main/${WRAPPER_FILENAME}`

/** Printed once per suppressed call; the count is the isolation marker. */
export const WRAPPER_MARKER = '[diag] suppressed login-item write'

export const WRAPPER_SOURCE = `// Generated by scripts/benchmark-electron-app.mjs; identical on every run and on both sides.
// Replaces app.setLoginItemSettings with a log line so a benchmark start cannot write HKCU.
const { app } = require('electron');
try {
  Object.defineProperty(app, 'setLoginItemSettings', {
    configurable: true,
    writable: true,
    value(settings) {
      console.log(${JSON.stringify(WRAPPER_MARKER)});
    }
  });
} catch {}
require('./${ENTRY_FILENAME}');
`

export function wrapperPath(appRoot) {
  return join(appRoot, 'out', 'main', WRAPPER_FILENAME)
}

export function sha256(text) {
  return createHash('sha256').update(text).digest('hex')
}

export function wrapperSha256() {
  return sha256(WRAPPER_SOURCE)
}

/**
 * Write the wrapper if it is missing or different. Returns what the evidence
 * needs: absolute path, sha256 of the bytes on disk, and whether this call had
 * to write anything.
 */
export function ensureWrapper(appRoot, { fileSystem = fs } = {}) {
  const file = wrapperPath(appRoot)
  fileSystem.mkdirSync(dirname(file), { recursive: true })
  let existing = null
  try {
    existing = fileSystem.readFileSync(file, 'utf8')
  } catch {
    existing = null
  }
  const written = existing !== WRAPPER_SOURCE
  if (written) fileSystem.writeFileSync(file, WRAPPER_SOURCE, 'utf8')
  return { file: WRAPPER_RELATIVE, absolutePath: file, sha256: wrapperSha256(), written, marker: WRAPPER_MARKER }
}

/** How many times the wrapper logged a suppressed write. */
export function countMarker(text, marker = WRAPPER_MARKER) {
  if (!text) return 0
  return String(text).split(marker).length - 1
}
