import { EventEmitter } from 'node:events'
import { PassThrough } from 'node:stream'
import { afterEach, beforeEach, describe, expect, it, vi } from 'vitest'
import { mergeSettings } from '@shared/defaults'

const mock = vi.hoisted(() => ({ spawn: vi.fn(), packaged: false }))
vi.mock('electron', () => ({ app: { get isPackaged() { return mock.packaged }, getAppPath: () => process.cwd() } }))
vi.mock('node:child_process', () => ({ spawn: mock.spawn }))
import { HotkeyHost } from './host'

function makeChild(kill = vi.fn()) {
  const child = Object.assign(new EventEmitter(), { stdin: new PassThrough(), stdout: new PassThrough(), stderr: new PassThrough(), postMessage: vi.fn(), kill })
  child.stdin.on('data', line => child.postMessage(JSON.parse(String(line))))
  return child
}
function reply(child: ReturnType<typeof makeChild>, event: object): void {
  child.stdout.write(JSON.stringify(event) + '\n')
}


describe('shortcut recording suspension', () => {
  beforeEach(() => { vi.clearAllMocks(); mock.packaged = false })
  afterEach(() => { vi.clearAllTimers(); vi.useRealTimers(); vi.unstubAllGlobals() })
  it('uses the development binary and restores state from split JSON pipe messages', () => {
    const child = makeChild(), event = vi.fn(), host = new HotkeyHost(event)
    mock.spawn.mockReturnValue(child)
    host.start(mergeSettings({}))
    expect(mock.spawn).toHaveBeenCalledWith(expect.stringMatching(/native[\\/]bin[\\/]yu-hotkey\.exe$/), [], expect.objectContaining({ windowsHide: true }))
    child.stdout.write('{"type":"rea'); child.stdout.write('dy"}\n{"type":"esc","at":1}\n')
    expect(child.postMessage).toHaveBeenCalledWith(expect.objectContaining({ type: 'config' }))
    expect(event).toHaveBeenCalledWith({ type: 'esc', at: 1 })
    host.stop()
  })
  it('reports only the current live helper PID for the resource panel', () => {
    const child = Object.assign(makeChild(), { pid: 123 }), host = new HotkeyHost(vi.fn())
    mock.spawn.mockReturnValue(child)
    expect(host.pid).toBeUndefined()
    host.start(mergeSettings({})); expect(host.pid).toBe(123)
    host.stop(); expect(host.pid).toBeUndefined()
  })
  it('locates the packaged binary outside ASAR', () => {
    mock.packaged = true
    vi.stubGlobal('process', { ...process, resourcesPath: 'E:/YU/resources' })
    const child = makeChild(), host = new HotkeyHost(vi.fn())
    mock.spawn.mockReturnValue(child)
    host.start(mergeSettings({}))
    expect(String(mock.spawn.mock.calls[0][0]).replaceAll('\\', '/')).toBe('E:/YU/resources/native/yu-hotkey.exe')
    host.stop()
  })
  it('restarts after an executable spawn failure and cancels the retry on stop', async () => {
    vi.useFakeTimers()
    const child = makeChild(), host = new HotkeyHost(vi.fn())
    mock.spawn.mockReturnValue(child)
    host.start(mergeSettings({}))
    child.emit('error', new Error('ENOENT')); child.emit('close', -4058)
    await vi.advanceTimersByTimeAsync(800)
    expect(mock.spawn).toHaveBeenCalledTimes(2)
    child.emit('close', 1); host.stop()
    await vi.advanceTimersByTimeAsync(1000)
    expect(mock.spawn).toHaveBeenCalledTimes(2)
  })
  it('terminates malformed output and a broken input pipe', () => {
    const child = makeChild(), host = new HotkeyHost(vi.fn())
    mock.spawn.mockReturnValue(child)
    host.start(mergeSettings({}))
    child.stdout.write('invalid json\n')
    expect(child.kill).toHaveBeenCalledTimes(1)
    child.stdin.emit('error', new Error('EPIPE'))
    expect(child.kill).toHaveBeenCalledTimes(2)
    host.stop()
  })
  it('terminates a native child that finishes spawning after suspension', () => {
    let spawned = false
    const child = makeChild(vi.fn(() => spawned))
    mock.spawn.mockReturnValue(child)
    const host = new HotkeyHost(vi.fn())
    host.start(mergeSettings({})); host.stop()
    expect(child.kill.mock.results.at(-1)?.value).toBe(false)
    spawned = true; child.emit('spawn')
    expect(child.kill.mock.results.at(-1)?.value).toBe(true)
  })
  it('does not acknowledge through a child stopped by the start handler', () => {
    const child = makeChild()
    mock.spawn.mockReturnValue(child)
    const host = new HotkeyHost(() => host.stop())
    host.start(mergeSettings({})); child.postMessage.mockClear()
    reply(child, { type: 'start', mode: 'dictation', at: 1 })
    expect(child.kill).toHaveBeenCalled()
    expect(child.postMessage).not.toHaveBeenCalled()
  })
  it('ignores events and exits from a stopped child after restarting', async () => {
    vi.useFakeTimers()
    const old = makeChild()
    const current = makeChild()
    mock.spawn.mockReturnValueOnce(old).mockReturnValue(current)
    const events = vi.fn(), host = new HotkeyHost(events)
    host.start(mergeSettings({})); host.stop(); host.start(mergeSettings({}))
    reply(old, { type: 'start', mode: 'dictation', at: 1 })
    old.emit('close', 0)
    await vi.advanceTimersByTimeAsync(1000)
    expect(events).not.toHaveBeenCalled()
    expect(mock.spawn).toHaveBeenCalledTimes(2)
    host.setActivity('working')
    expect(current.postMessage).toHaveBeenCalledWith({ type: 'activity', value: 'working' })
    host.stop()
  })
  it('suspends voice shortcuts during screenshot editing and preserves suspension across config updates', () => {
    const child = makeChild()
    mock.spawn.mockReturnValue(child)
    const host = new HotkeyHost(vi.fn()), settings = mergeSettings({})
    host.start(settings); reply(child, { type: 'ready' })
    host.setSuspended(true)
    host.setCapturing(false)
    expect(child.postMessage).toHaveBeenLastCalledWith({ type: 'enabled', value: false })
    host.apply(settings)
    expect(child.postMessage.mock.calls.filter(([msg]) => msg.type === 'enabled').at(-1)?.[0]).toMatchObject({ value: false })
    host.setSuspended(false)
    expect(child.postMessage).toHaveBeenLastCalledWith({ type: 'enabled', value: true })
    host.stop()
  })
  it('acknowledges a rejected start with the unchanged actual processing state', () => {
    const child = makeChild()
    mock.spawn.mockReturnValue(child)
    const host = new HotkeyHost(vi.fn())
    host.start(mergeSettings({})); reply(child, { type: 'ready' })
    host.setActivity('working')
    child.postMessage.mockClear()
    reply(child, { type: 'start', mode: 'dictation', at: 1 })
    expect(child.postMessage).toHaveBeenLastCalledWith({ type: 'activity', value: 'working' })
    host.stop()
  })
  it('mirrors the actual task activity and restores it when the child becomes ready', () => {
    const child = makeChild()
    mock.spawn.mockReturnValue(child)
    const host = new HotkeyHost(vi.fn())
    host.setActivity('recording')
    host.start(mergeSettings({})); reply(child, { type: 'ready' })
    expect(child.postMessage).toHaveBeenCalledWith({ type: 'activity', value: 'recording' })
    child.postMessage.mockClear()
    host.setActivity('recording')
    expect(child.postMessage).not.toHaveBeenCalled()
    host.setActivity('working'); host.setActivity('idle')
    expect(child.postMessage.mock.calls.map(([message]) => message.value)).toEqual(['working', 'idle'])
    host.stop()
  })
  it('temporarily disables capture without changing the persisted enabled flag and respects settings updates', () => {
    const child = makeChild()
    mock.spawn.mockReturnValue(child)
    const host = new HotkeyHost(vi.fn()), settings = mergeSettings({})
    host.start(settings); reply(child, { type: 'ready' })
    host.setCapturing(true)
    expect(child.postMessage).toHaveBeenCalledWith({ type: 'capture', active: true })
    reply(child, { type: 'capture-key', token: 'RightShift', down: true })
    expect(child.postMessage).toHaveBeenLastCalledWith({ type: 'enabled', value: false })
    host.apply(settings)
    expect(child.postMessage.mock.calls.filter(call => call[0].type === 'enabled').at(-1)?.[0].value).toBe(false)
    host.setCapturing(false)
    expect(child.postMessage).toHaveBeenLastCalledWith({ type: 'enabled', value: true })
    host.apply({ ...settings, hotkeys: { ...settings.hotkeys, enabled: false } })
    host.setCapturing(true); host.setCapturing(false)
    expect(child.postMessage).toHaveBeenLastCalledWith({ type: 'enabled', value: false })
    expect(settings.hotkeys.enabled).toBe(true)
    host.stop()
  })
})
